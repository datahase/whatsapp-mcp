#!/usr/bin/env bash
# Regenerates THIRD_PARTY_LICENSES.txt with the full license text of every Go
# module linked into the binary. Run after changing dependencies.
set -euo pipefail
cd "$(dirname "$0")/.."
out=THIRD_PARTY_LICENSES.txt
{
  echo "Full license texts of Go modules linked into whatsapp-mcp."
  echo "Generated by scripts/third-party-licenses.sh. Do not edit by hand."
  for m in $(go list -deps -f '{{if .Module}}{{.Module.Path}}@{{.Module.Version}}{{end}}' ./cmd/whatsapp-mcp | sort -u | grep -v '^whatsapp-mcp'); do
    dir="$(go env GOMODCACHE)/$m"
    for f in $(ls "$dir" | grep -iE '^(licen[cs]e|copying|notice)' || true); do
      printf '\n\n==================== %s (%s) ====================\n\n' "$m" "$f"
      cat "$dir/$f"
    done
  done
} > "$out"
echo "wrote $out"
